// Bundles mcp/blender_kit_mcp/handlers/*.py in dependency order into
// skills/blender-setup/templates/scripts/blender_kit_ops.py for offline Script Mode.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const handlersDir = path.join(root, "mcp", "blender_kit_mcp", "handlers");
const outPath = path.join(root, "skills", "blender-setup", "templates", "scripts", "blender_kit_ops.py");

const ORDER = [
  "session_store.py",
  "modeling_subd.py",
  "target_compile.py",
  "node_graphs.py",
  "rigging_anim.py",
  "audits.py",
];

const INTERNAL_MODULES = new Set([
  "session_store",
  "modeling_subd",
  "target_compile",
  "node_graphs",
  "rigging_anim",
  "audits",
]);

function stripInternalImports(src) {
  const lines = src.split(/\r?\n/);
  const out = [];
  let skipTryBlock = false;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (/^try:\s*$/.test(line) && i + 1 < lines.length && /^\s+from \.[a-z0-9_]+ import/.test(lines[i + 1])) {
      skipTryBlock = true;
      continue;
    }
    if (skipTryBlock) {
      if (line.trim() === "" && i > 0 && !lines[i - 1].trim().endsWith(":")) {
        skipTryBlock = false;
      }
      continue;
    }
    const m = line.match(/^from (\.?[a-z0-9_]+) import/);
    if (m && INTERNAL_MODULES.has(m[1].replace(/^\./, ""))) {
      continue;
    }
    out.push(line);
  }
  return out.join("\n");
}

const chunks = [
  "# Auto-generated by scripts/sync-ops.mjs from mcp/blender_kit_mcp/handlers/.",
  "# Single source of truth for both live MCP Mode and offline Script Mode.",
];

for (const fname of ORDER) {
  const fpath = path.join(handlersDir, fname);
  const raw = fs.readFileSync(fpath, "utf8");
  chunks.push(`\n# --- ${fname} ---\n` + stripInternalImports(raw).trim());
}

chunks.push(`
NATIVE_HANDLER_MAP = {
    "kit_session_manage": kit_session_manage,
    "kit_checkpoint": kit_checkpoint,
    "kit_create_primitive": kit_create_primitive,
    "kit_bmesh_edit": kit_bmesh_edit,
    "kit_subd_and_loops": kit_subd_and_loops,
    "kit_compile_target": kit_compile_target,
    "kit_transform_and_assemble": kit_transform_and_assemble,
    "kit_modifier": kit_modifier,
    "kit_curve_tube": kit_curve_tube,
    "kit_node_graph_build": kit_node_graph_build,
    "kit_uv_unwrap": kit_uv_unwrap,
    "kit_material_preset": kit_material_preset,
    "kit_add_gleam_effect": kit_add_gleam_effect,
    "kit_rig_build_armature": kit_rig_build_armature,
    "kit_pro_motion": kit_pro_motion,
    "kit_clean_and_strip_shells": kit_clean_and_strip_shells,
    "kit_optimize_quads_to_tris": kit_optimize_quads_to_tris,
    "kit_audit_run_isolated": kit_audit_run_isolated,
}
`);

fs.writeFileSync(outPath, chunks.join("\n") + "\n", "utf8");
console.log(`Synced ${ORDER.length} handler modules -> skills/blender-setup/templates/scripts/blender_kit_ops.py`);
